// Фильтр мусорных «адресов» из постов-источников (dot-events).
// Организаторы пишут «уточняйте у организаторов», «север», «локация при записи» —
// это не адрес: в карточке такое поле врёт и сбивает геокодер.
// Проверка: node scripts/dot-addr-junk-check.mjs
import { cleanCardText } from './text-safe.mjs';

/** Ведущий служебный ярлык: «Где:», «Локация:», «Адрес — », «Место проведения:», «Where:». */
const LABEL = /^(?:где|where|локаци[яи]|адрес|место(?:\s+проведени[яе])?|проведени[яе]|place)\s*[:—-]\s*/i;

const JUNK = [
  /при\s+записи/i,
  /после\s+записи/i,
  /(?:после|при|во\s+время)\s+регистрац/i,
  /^(?:tba|tbc|tbd)\.?$/i,
  /адрес\s+(отправим|пришл|вышл|сообщ|будет|позже|уточн)/i,
  /(отправим|пришл[её]м|сообщим)\s+адрес/i,
  /уточня(?:й|йте|ем|емся|ется|ть)/i,
  /у\s+организатор/i,
  /у\s+администратор/i,
  /^мост(?=[\s,(]|$)/i,
  /^кольцо(?=[\s,(]|$)/i,
  /(^|[\s,])мост\s+на\s+(западе|востоке|севере|юге)/i,
  /где-?то/i,
  /~?\s*\d+\s*км\s+от/i,
  /^\d+\s*м\s+от/i,
  /точн[а-яё]*\s+(адрес|место|локаци)/i,
  /локац[а-яё]*\s+(пришл|отправл|скин|сообщ|уточн)/i,
  /(пришл[юеё]м?|отправлю|скин[уе]|сообщу)\s+(?:в\s+)?личк/i,
  /(пришл[юеё]м?|отправлю|скин[уе]|сообщу)\s+в\s+(?:лс|dm|личн|сообщени)/i,
  /^загородн[а-яё]*[\s,.-]*(?:эко|eco)/i,
  /^(?:север|юг|восток|запад|центр|центр города)$/i,
  /^(?:север|юг|восток|запад|центр)(\s*\(.*\))?\s*$/i,
  // «адрес» = сырые координаты поста («16.0428842,108.2518050») — это не адрес, а сам пин
  /^\s*(?:[a-z]{1,2}=)?-?\d{1,3}[.,]\d{3,}\s*[;,]?\s*-?\d{1,3}[.,]\d{3,}\s*$/i,
  // место сбора вместо адреса: «Сбор: здесь (центр)», «сбор у входа»
  /^сбор[а-яё]*(?=[\s,:—-]|$)/i,
  /(^|[\s,(])(здесь|тут)(?=[\s,).!]|$)/i,
  // «место проведения» без адреса: «На берегу залива», «на берегу озера»
  /^на\s+берегу(?=[\s,(]|$)/i,
  // служебная заметка поста вместо адреса: «Важно: формат встречи не является личной психотерапией…», «Внимание: …»
  /^(?:важно|внимание|примечание|note|nb|обратите\s+внимание)\s*[:.—-]/i,
  // ссылка (карта/пост) вместо адреса: «https://maps.app.goo.gl/…», «t.me/…» — это не улица (кейс 999, fa208f0c)
  /^(?:https?:\/\/|www\.|t\.me\/)/i,
  // «адрес» = отсылка к телефону/карте вместо улицы: «Please check the exact address by phone, Canggu», «на карте» (кейс 1069)
  /(?:please\s+)?check\s+(?:the\s+)?exact\s+address/i,
  /address\s+(?:by|via)\s+phone/i,
  /^на\s+карте(?=[\s,(]|$)/i,
  /^на\s+карте\s/i,
  // «адрес» = только СТРАНА (в т.ч. повтор «Cyprus, Cyprus») — улицы в нём нет (кейс 1085, 89e345be).
  // Настоящие адреса с городом/улицей («Nicosia, Cyprus», «Лимасол, Кипр») правило не трогает.
  /^(?:кипр|cyprus|вьетнам|vietnam|индонезия|indonesia)\s*(?:,\s*(?:кипр|cyprus|вьетнам|vietnam|индонезия|indonesia))?$/i,
  // «адрес» = только ДАТА и/или ВРЕМЯ поста: «25.11.26 в 13:00», «8 ноября 18:00», «Суббота, 22.11 в 11:00» (кейс 1052, 1e7707ff).
  // Узко: строка целиком состоит из даты (DD.MM[.YY]) или «DD <месяц>» плюс необязательное время — иначе не трогаем,
  // иначе пострадают настоящие адреса с номерами («28 Oktovriou 259», «115 Đặng Vũ Hỷ»).
  /^(?:#?дата\s*[:.—-]\s*)?(?:(?:понедельник|вторник|сред[ауы]|четверг|пятниц[ауы]|суббот[ауы]|воскресенье)\s*,?\s*)?\d{1,2}[./]\d{1,2}(?:[./]\d{2,4})?(?:\s*(?:г\.?|года))?(?:\s*,?\s*(?:\(?(?:понедельник|вторник|сред[ауы]|четверг|пятниц[ауы]|суббот[ауы]|воскресенье)\)?))?(?:\s*(?:(?:в|at|начало|start|@)\s*)?\d{1,2}[:.]\d{2}(?:\s*[-–—]\s*\d{1,2}[:.]\d{2})?)?$/i,
  /^(?:(?:понедельник|вторник|сред[ауы]|четверг|пятниц[ауы]|суббот[ауы]|воскресенье)\s*,?\s*)?\d{1,2}\s+(?:январ[яе]|феврал[яе]|марта?|апрел[яе]|ма[яе]|июн[яе]|июл[яе]|августа?|сентябр[яе]|октябр[яе]|ноябр[яе]|декабр[яе])(?:\s+\d{4})?(?:\s*(?:(?:в|at)\s*)?\d{1,2}[:.]\d{2})?$/i,
];

/** Абзац текста поста вместо адреса: длинно, без цифр (номера дома/индекса), много слов.
 *  Кейс 999 (8506a6b0): «Большинство иностранных предпринимателей во Вьетнаме идут по пути…».
 *  Легитимные длинные адреса Bali/Кипра всегда несут цифры (номер дома или индекс). */
function isProseAddress(s) {
  if (s.length < 100 || /\d/.test(s)) return false;
  const words = s.split(/\s+/).filter(Boolean).length;
  if (words < 12) return false;
  // у адресов-склеек (площадка + улица + город) много запятых; у абзаца текста — тире/мало запятых
  const commas = (s.match(/,/g) || []).length;
  return /\s—\s/.test(s) || commas === 0;
}

/** true — «адрес» это просто название города («Нячанг», «Дананг, Вьетнам»): улицы в нём нет. */
export function isCityAddress(raw, city) {
  const a = normCity(raw);
  if (!a) return false;
  const c = normCity(city);
  if (c && a === c) return true;
  // «г. Нячанг», «город Дананг», «Nha Trang, Vietnam» → снять служебное и хвост страны
  const a2 = a.replace(/^(?:г|город|city)\.?\s*/, '').replace(/\s*,?\s*(?:vietnam|вьетнам|кипр|cyprus|индонезия|indonesia)$/, '').trim();
  return !!c && a2 === c;
}

function normCity(raw) {
  if (!raw) return '';
  return String(raw).toLowerCase().replace(/ё/g, 'е').replace(/[.,;:!?—–-]+/g, ' ').replace(/\s+/g, ' ').trim();
}

/** Адрес для карточки: мусор → null, иначе строка без служебного ярлыка. */
export function isJunkAddress(raw) {
  const s = stripAddressLabel(raw);
  if (!s || s.length < 3) return true;
  if (isProseAddress(s)) return true;
  return JUNK.some((re) => re.test(s));
}

/** Снимает ярлык и хвостовую пунктуацию/эмодзи; возвращает '' если ничего не осталось. */
export function stripAddressLabel(raw) {
  if (!raw) return '';
  let s = String(raw).trim();
  s = s.replace(/[.,;:!?\s❤🧡💛💚💙💜🤍🖤]+$/gu, '').trim();
  s = s.replace(LABEL, '').trim();
  s = s.replace(/[.,;:!?\s]+$/g, '').trim();
  return s;
}

/** Адрес для карточки: мусор → null, иначе строка без служебного ярлыка. */
export function cleanAddress(raw) {
  if (isJunkAddress(raw)) return null;
  return cleanCardText(stripAddressLabel(raw)) || null;
}
