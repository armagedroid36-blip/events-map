// Фильтр мусорных «адресов» из постов-источников (dot-events).
// Организаторы пишут «уточняйте у организаторов», «север», «локация при записи» —
// это не адрес: в карточке такое поле врёт и сбивает геокодер.
// Проверка: node scripts/dot-addr-junk-check.mjs

/** Ведущий служебный ярлык: «Где:», «Локация:», «Адрес — », «Место проведения:», «Where:». */
const LABEL = /^(?:где|where|локаци[яи]|адрес|место(?:\s+проведени[яе])?|проведени[яе]|place)\s*[:—-]\s*/i;

const JUNK = [
  /при\s+записи/i,
  /после\s+записи/i,
  /(?:после|при|во\s+время)\s+регистрац/i,
  /^(?:tba|tbc|tbd)\.?$/i,
  /адрес\s+(отправим|пришл|вышл|сообщ|будет|позже|уточн)/i,
  /(отправим|пришл[её]м|сообщим)\s+адрес/i,
  /уточня(?:й|йте|ем|емся|ется|ть)/i,
  /у\s+организатор/i,
  /у\s+администратор/i,
  /^мост(?=[\s,(]|$)/i,
  /^кольцо(?=[\s,(]|$)/i,
  /(^|[\s,])мост\s+на\s+(западе|востоке|севере|юге)/i,
  /где-?то/i,
  /~?\s*\d+\s*км\s+от/i,
  /^\d+\s*м\s+от/i,
  /точн[а-яё]*\s+(адрес|место|локаци)/i,
  /локац[а-яё]*\s+(пришл|отправл|скин|сообщ|уточн)/i,
  /(пришл[юеё]м?|отправлю|скин[уе]|сообщу)\s+(?:в\s+)?личк/i,
  /(пришл[юеё]м?|отправлю|скин[уе]|сообщу)\s+в\s+(?:лс|dm|личн|сообщени)/i,
  /^загородн[а-яё]*[\s,.-]*(?:эко|eco)/i,
  /^(?:север|юг|восток|запад|центр|центр города)$/i,
  /^(?:север|юг|восток|запад|центр)(\s*\(.*\))?\s*$/i,
  // «адрес» = сырые координаты поста («16.0428842,108.2518050») — это не адрес, а сам пин
  /^\s*(?:[a-z]{1,2}=)?-?\d{1,3}[.,]\d{3,}\s*[;,]?\s*-?\d{1,3}[.,]\d{3,}\s*$/i,
  // место сбора вместо адреса: «Сбор: здесь (центр)», «сбор у входа»
  /^сбор[а-яё]*(?=[\s,:—-]|$)/i,
  /(^|[\s,(])(здесь|тут)(?=[\s,).!]|$)/i,
  // «место проведения» без адреса: «На берегу залива», «на берегу озера»
  /^на\s+берегу(?=[\s,(]|$)/i,
];

/** true — «адрес» это просто название города («Нячанг», «Дананг, Вьетнам»): улицы в нём нет. */
export function isCityAddress(raw, city) {
  const a = normCity(raw);
  if (!a) return false;
  const c = normCity(city);
  if (c && a === c) return true;
  // «г. Нячанг», «город Дананг», «Nha Trang, Vietnam» → снять служебное и хвост страны
  const a2 = a.replace(/^(?:г|город|city)\.?\s*/, '').replace(/\s*,?\s*(?:vietnam|вьетнам|кипр|cyprus|индонезия|indonesia)$/, '').trim();
  return !!c && a2 === c;
}

function normCity(raw) {
  if (!raw) return '';
  return String(raw).toLowerCase().replace(/ё/g, 'е').replace(/[.,;:!?—–-]+/g, ' ').replace(/\s+/g, ' ').trim();
}

/** Адрес для карточки: мусор → null, иначе строка без служебного ярлыка. */
export function isJunkAddress(raw) {
  const s = stripAddressLabel(raw);
  if (!s || s.length < 3) return true;
  return JUNK.some((re) => re.test(s));
}

/** Снимает ярлык и хвостовую пунктуацию/эмодзи; возвращает '' если ничего не осталось. */
export function stripAddressLabel(raw) {
  if (!raw) return '';
  let s = String(raw).trim();
  s = s.replace(/[.,;:!?\s❤🧡💛💚💙💜🤍🖤]+$/gu, '').trim();
  s = s.replace(LABEL, '').trim();
  s = s.replace(/[.,;:!?\s]+$/g, '').trim();
  return s;
}

/** Адрес для карточки: мусор → null, иначе строка без служебного ярлыка. */
export function cleanAddress(raw) {
  if (isJunkAddress(raw)) return null;
  return stripAddressLabel(raw);
}
