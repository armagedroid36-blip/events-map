// Юнит: точка как разделитель времени в постах TG-афиш («9.00-10.30»).
// Кейс dot 1083: пост t.me/nyachang_ru/26529 «Йога в Нячанге … Четверг, 26 ноября … 9.00-10.30»
// дал карточку без start_time. Правило должно брать парный диапазон с «круглыми» минутами
// и НЕ превращать диапазон дат «21.11-22.11» во время 21:11 (питфол 18.11.2026).
import { parseDate } from './collect-tg.mjs';

const cases = [
  ['Занятие 9.00-10.30 у моря, четверг 26 ноября', '09:00'],
  ['тренировка 7.30-9.00, суббота 26.11', '07:30'],
  ['ночёвка 21.11-22.11 в горах', null],
  ['фестиваль с 9.11-10.11, среда 26 ноября', null],
  ['начало 18:30, пятница 27 ноября', '18:30'],
  ['вечер 20-00 суббота 28 ноября', '20:00'],
];

let ok = 0;
for (const [text, want] of cases) {
  const got = (parseDate(text) || {}).time ?? null;
  const pass = got === want;
  if (pass) ok++;
  console.log(`${pass ? 'OK  ' : 'FAIL'} ${JSON.stringify(text)} -> ${got} (ожидалось ${want})`);
}
console.log(`${ok}/${cases.length}`);
if (ok !== cases.length) process.exit(1);
