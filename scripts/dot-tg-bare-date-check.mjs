// Юнит: ветка 2 parseDate (голый DD.MM/DD.MM.YY) в scripts/collect-tg.mjs.
// До правки 24.10.2026 прошедшая пара чисел молча проваливалась в ветку «день недели»
// и давала +7 дней: «ПЯТНИЦА | 23.10 | 11:00» → 30.10, т.е. прошедший пост
// публиковался как предстоящий (тот же корень, что у ярлыка #дата, карточка 8167746c).
// Запуск: node --env-file=.env scripts/dot-tg-bare-date-check.mjs
process.env.COLLECT_TG_NO_RUN = '1';
const { parseDate } = await import('./collect-tg.mjs');

const cases = [
  ['прошедшая дата без года + день недели -> пост устарел', 'ПЯТНИЦА | 23.10 | 11:00\nВстреча в пятницу, ждём вас', null],
  ['серия: первая пара в прошлом, дальше будущее -> первая будущая', 'Занятия: 05.10, 12.10, 19.10, 26.10 в 10:00', '2026-10-26'],
  ['09.30 — не дата (месяц 30), работает день недели', 'Пятница 19:00, сбор в 09.30 утра', '2026-10-30'],
  ['«2.5 км» не считается датой', 'Суббота 19:00, 2.5 км от центра', '2026-10-31'],
  ['прошедшая дата с годом -> пост устарел', 'Праздник 13.10.2026 в 18:00', null],
  ['дата в далёком прошлом без года -> следующий год', 'Встреча 05.01 в 12:00', '2027-01-05'],
  ['будущая дата берётся как раньше', 'Концерт 30.10 в 20:00', '2026-10-30'],
];

let ok = 0;
for (const [name, text, want] of cases) {
  const got = parseDate(text);
  const gotDate = got ? got.date : null;
  const pass = gotDate === want;
  if (pass) ok++;
  console.log(`${pass ? 'OK  ' : 'FAIL'} | ${name} -> ${JSON.stringify(got)}${pass ? '' : ` (ждали ${want})`}`);
}
console.log(`\n${ok}/${cases.length}`);
process.exit(ok === cases.length ? 0 : 1);
