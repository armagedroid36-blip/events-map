// Юнит-проверка extractTitle на реальных зачинах постов TG-афиш.
// COLLECT_TG_NO_RUN=1 node scripts/dot-tg-title-check.mjs
process.env.COLLECT_TG_NO_RUN = '1';
const { extractTitle } = await import('./collect-tg.mjs');

const cases = [
  // [вход, ожидание (подстрока), описание]
  ['Всем привет!\nПриглашаю вас на завтрак с расстановками\n29 встреча.\nТема встречи - отношения', 'Завтрак с расстановками', 'Дананг 5718 (карточка 577fc414)'],
  ['Друзья, приглашаем на художественную выставку «Истина Доброты»\n16:00', 'Художественную выставку', 'Нячанг 22948'],
  ['Друзья!\nКонцерт группы «Мозаика» в ресторане 369\n19:00', 'Концерт группы', 'Дананг 5658'],
  ['Hello guys!\nStand-up вечер в Chez Hoa\n14:00', 'Stand-up вечер', 'Дананг 5212'],
  ['Привет!\nМастер-класс по импровизации\n01.10 19:00', 'Мастер-класс', 'Нячанг 23928'],
  ['Добрый день! Собираемся завтра на игру ТАС в ресторане 369, будет весело', 'Собираемся завтра на игру ТАС', 'Дананг 5520'],
  ['Мозгобойня в Дананге: квиз 09.10\nЗапись в лс', 'Мозгобойня в Дананге', 'обычный пост без приветствия'],
  ['#дата: 9.10\nМедитация на пляже', 'Медитация на пляже', 'зачин-тег пропускается'],
  ['Всем привет!', 'Событие в', 'только приветствие — фолбэк'],
];

let pass = 0;
for (const [input, expect, note] of cases) {
  const got = extractTitle(input);
  const ok = got.includes(expect);
  if (ok) pass++;
  console.log(`${ok ? 'OK ' : 'FAIL'} | «${got}» | ожидание «${expect}» | ${note}`);
}
console.log(`\nИтог: ${pass}/${cases.length} пройдено`);
process.exit(pass === cases.length ? 0 : 1);
