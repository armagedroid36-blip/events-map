// dot-town-snap-check.mjs — юнит правила «метка-ОКРУГ от источника → ГОРОДОК по точке»
// (collect-cyprus.mjs, ветка Cyprus Now; порог TOWN_SNAP_KM = 3 км, только внутри своего округа).
//
// Зачем: Cyprus Now пишет city «Famagusta» событиям Ая-Напы/Протараса/Паралимни, из-за чего
// фильтр по городу на карте расщеплялся (Ая-Напа 29 живых карточек против 20 «Фамагуста», run 269).
// Проверка держит обе границы: городки снапятся, а село Сотира (3.5 км от Паралимни) — нет.
import { snapDistrictLabel } from './cy-districts.mjs';

const cases = [
  ['Strata Street Party (Ая-Напа, 0.4 км)', 'Фамагуста', 34.9906221, 33.9940139, 'Ая-Напа'],
  ['Protaras SwimRun (Протарас, 0.02 км)', 'Фамагуста', 35.0120718, 34.0562252, 'Протарас'],
  ['NYE Diamonds Showbar (1.3 км от Протараса)', 'Фамагуста', 35.0183977, 34.0447004, 'Протарас'],
  ['Golden Coast Beach Hotel (3.2 км от Протараса — на границе, не снапим)', 'Фамагуста', 35.037456, 34.037347, 'Фамагуста'],
  ['Sotira Municipal Theatre (3.5 км — НЕ снапим)', 'Фамагуста', 35.0284699, 33.9513191, 'Фамагуста'],
  ['Фамагуста, центр города', 'Фамагуста', 35.12, 33.943, 'Фамагуста'],
  ['Паралимни, центр', 'Фамагуста', 35.0397, 33.9819, 'Паралимни'],
  ['Пафос, центр', 'Пафос', 34.7754, 32.4245, 'Пафос'],
  ['Полис (округ Пафос)', 'Пафос', 35.0363, 32.4255, 'Полис'],
  ['Лимасол — правило не работает', 'Лимасол', 34.7071, 33.0226, 'Лимасол'],
  ['Городок в ЧУЖОМ округе не берём (Ларнака + точка Ая-Напы)', 'Ларнака', 34.9906221, 33.9940139, 'Ларнака'],
  ['Кипр вне списка центров (Никосия)', 'Никосия', 35.1856, 33.3823, 'Никосия'],
];

let ok = 0, bad = 0;
for (const [name, city, lat, lng, expect] of cases) {
  const got = snapDistrictLabel(city, lat, lng);
  const pass = got === expect;
  pass ? ok++ : bad++;
  console.log(`${pass ? 'OK  ' : 'FAIL'} | ${name}: «${city}» -> «${got}» (ожидалось «${expect}»)`);
}
console.log(`\n${ok}/${cases.length} ok, провалов ${bad}`);
process.exit(bad ? 1 : 0);
