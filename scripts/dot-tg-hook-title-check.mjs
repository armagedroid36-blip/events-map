// Юнит: строка-хук не становится названием события (класс 985).
// Запуск: COLLECT_TG_NO_RUN=1 node scripts/dot-tg-hook-title-check.mjs
process.env.COLLECT_TG_NO_RUN = '1';
process.env.DRY_RUN = '1';
import { extractTitle } from './collect-tg.mjs';

const cases = [
  // 1. хука-вопрос + приглашение с названием-предметом
  ['🕵️‍♀️ Любите квизы и хотите разнообразить привычный формат?\nПриходите на детективное расследование Detectit с элементами тру-крайма, квеста\n📆 21.11',
   (t) => !t.includes('?') && /Detectit/i.test(t)],
  // 2. хук, следующая строка — продолжение фразы с маленькой буквы ⇒ оставляем как есть
  ['Го на инглиш bla-bla brunch?\nв это Воскресенье снова с Карлосом\n#дата: 22.11',
   (t) => t === 'Го на инглиш bla-bla brunch?'],
  // 3. вопрос-тема + абзац-описание ⇒ название не меняем (абзац не годится)
  ['Кому Авито приносит деньги, а кому туда лучше даже не заходить?\nЛюбой канал трафика — это не волшебная таблетка, а математика.',
   (t) => t === 'Кому Авито приносит деньги, а кому туда лучше даже не заходить?'],
  // 4. КАПС-вопрос + приглашение с именем в кавычках ⇒ берём имя
  ['Я ТАК ХОЧУ БЛИЗОСТИ. ПОЧЕМУ ЖЕ МНЕ ХОЧЕТСЯ СБЕЖАТЬ, КАК ТОЛЬКО ОНА ПОЯВЛЯЕТСЯ?\nПриглашаю мужчин и женщин в лабораторию близости «За пределами слов». Через телесные практики.',
   (t) => t === 'За пределами слов'],
  // 5. контроль: обычное название не трогаем
  ['Йога на рассвете\n7:00 на пляже', (t) => t === 'Йога на рассвете'],
  // 6. контроль: приглашение без хука остаётся названием
  ['Приглашаем на мастер-класс по керамике', (t) => t === 'Мастер-класс по керамике'],
  // 7. контроль: короткий вопрос без адресата и без следующей строки
  ['Любите квизы?', (t) => t === 'Любите квизы?'],
  // 8. контроль: «Планы на субботу: …?» — хук, но приличной замены нет
  ['Планы на субботу: промокнуть на массаж?\n📍 Нячанг', (t) => !t.startsWith('Планы') || t.includes('массаж')],
];

let ok = 0;
for (const [i, [text, check]] of cases.entries()) {
  let got;
  try { got = extractTitle(text); } catch (e) { got = `ОШИБКА: ${e.message}`; }
  const pass = check(got);
  if (pass) ok++;
  console.log(`${pass ? 'OK  ' : 'FAIL'} ${i + 1}: «${got}»`);
}
console.log(`ИТОГ ${ok === cases.length ? 'OK' : 'ПРОВАЛ'} ${ok}/${cases.length}`);
process.exit(ok === cases.length ? 0 : 1);
