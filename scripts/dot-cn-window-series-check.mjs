// Юнит isWindowSeries (cn-window-series.mjs): окно тура/серии не считается дублем записи.
import { isWindowSeries } from './cn-window-series.mjs';

const T = (start, end, title = 'x') => ({ start, end, title });
let ok = 0; let fail = 0;
const t = (name, got, want) => {
  if (got === want) { ok++; console.log(`ok   ${name}`); }
  else { fail++; console.log(`FAIL ${name}: got ${got}, want ${want}`); }
};

// 1. Окно 22→24 + отдельные вечера 23 и 24 (Μια νύκτα στον παράδεισο, Пафос)
t('окно + два вечера',
  isWindowSeries([T('2027-01-22T18:30', '2027-01-24T18:30'), T('2027-01-23T18:30', null), T('2027-01-24T18:30', null)]), true);

// 2. Окно тура 06.11→09.12 + конкретный вечер 08.11 (Μαντάμ Μαριάννα)
t('окно тура + вечер',
  isWindowSeries([T('2026-11-06T18:30', '2026-12-09T18:30'), T('2026-11-08T17:00', null)]), true);

// 3. ДВЕ записи с одной датой начала — возможный дубль, окном не объясняется
t('одна дата дважды — не окно',
  isWindowSeries([T('2026-11-06T18:30', '2026-12-09T18:30'), T('2026-11-06T20:30', null)]), false);

// 4. Две записи одного дня без интервала (кейс 215) — не окно
t('пара без интервала',
  isWindowSeries([T('2026-12-12T10:00', null), T('2026-12-12T10:00', null)]), false);

// 5. Интервал НЕ накрывает вторую дату — это не контейнер
t('интервал не накрывает',
  isWindowSeries([T('2026-11-01T10:00', '2026-11-02T18:00'), T('2026-11-05T19:00', null)]), false);

// 6. Одна запись — вырожденный случай
t('одна запись', isWindowSeries([T('2026-11-01T10:00', '2026-11-02T18:00')]), false);

// 7. Пустой/битый вход
t('пустой массив', isWindowSeries([]), false);
t('нет start', isWindowSeries([T('', '2026-11-02'), T('2026-11-03', null)]), false);

// 8. Три равные даты (серия в один день) — не окно
t('три записи одна дата',
  isWindowSeries([T('2026-11-07T19:00', '2026-11-09T19:00'), T('2026-11-07T19:00', null), T('2026-11-08T19:00', null)]), false);

console.log(`\n${ok}/${ok + fail} ok, FAIL ${fail}`);
process.exit(fail ? 1 : 0);
